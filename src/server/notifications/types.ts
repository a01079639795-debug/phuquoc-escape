/**
 * Порт уведомлений.
 *
 * В MVP канал один — Telegram. Порт нужен не ради абстракции: без него
 * проверить, что при создании заявки менеджер получает сообщение, можно было
 * бы только реальной отправкой в реальный чат.
 *
 * Электронная почта на этом этапе не реализуется по договорённости; она
 * добавляется новой реализацией этого же интерфейса.
 */

export type Notification = {
  /** Текст с разметкой HTML в объёме, который понимает Telegram. */
  text: string;
  /** Для логов и тестов: что за событие. */
  kind: 'request.created';
};

export interface NotifierPort {
  readonly kind: string;
  /** Не бросает исключений: сбой доставки не должен ломать основную операцию. */
  send(notification: Notification): Promise<void>;
}
